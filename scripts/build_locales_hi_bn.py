def build() -> None:
    for locale,pages in PAGES.items():
        target = SITE / locale
        target.mkdir(parents=True, exist_ok=True)
        for page in CORE_PAGES:
            (target/page).write_text(page_html(locale,page,pages[page]),encoding="utf-8")
    print("Built staged HI/BN core translations:", len(CORE_PAGES)*2, "pages")


if __name__ == "__main__":
    build()
